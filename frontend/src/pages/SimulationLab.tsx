import React, { useState } from 'react';
import { SimulationScenario, SimulationExecutionResult } from '../types/index.js';
import { 
  Play, 
  Terminal, 
  ShieldAlert, 
  Zap, 
  Flame, 
  ArrowRight, 
  CheckCircle2, 
  RotateCcw,
  Sparkles
} from 'lucide-react';

interface SimulationLabProps {
  scenarios: SimulationScenario[];
  onExecuteScenario: (scenarioId: string) => Promise<SimulationExecutionResult>;
  onNavigateToIncident: (incidentId: string) => void;
  onReset: () => void;
  isResetting: boolean;
}

export const SimulationLab: React.FC<SimulationLabProps> = ({
  scenarios,
  onExecuteScenario,
  onNavigateToIncident,
  onReset,
  isResetting,
}) => {
  const [runningScenarioId, setRunningScenarioId] = useState<string | null>(null);
  const [lastResult, setLastResult] = useState<SimulationExecutionResult | null>(null);
  const [terminalLogs, setTerminalLogs] = useState<string[]>([
    '[INIT] Simulation Lab Sandboxed Harness Ready.',
    '[INFO] Telemetry generated by simulations is strictly tagged with isSimulated: true.',
    '[READY] Select any scenario below to trigger synthetic adversary sequences.',
  ]);

  const handleRun = async (scenario: SimulationScenario) => {
    setRunningScenarioId(scenario.id);
    setTerminalLogs(prev => [
      ...prev,
      `[SIM_START] Launching scenario: ${scenario.name} (Adversary IP: ${scenario.attackerIp})`,
      `[INJECTING] Generating ${scenario.eventsCount} telemetry events...`
    ]);

    try {
      const res = await onExecuteScenario(scenario.id);
      setLastResult(res);

      setTerminalLogs(prev => [
        ...prev,
        `[INJECT_DONE] Successfully ingested ${res.injectedEventsCount} events through Ingestion API.`,
        ...res.triggeredRules.map((r: string) => `[DETECTION_ALERT] Triggered Sigma Rule: ${r}`),
        `[CORRELATION] Incident correlated: ${res.correlatedIncidentId || 'None'} with Risk Score: ${res.riskScore}/100`,
        `[SOAR_EVAL] Automated defensive policy evaluated. Duration: ${res.durationMs}ms`,
        `[COMPLETED] Scenario finished.`
      ]);
    } catch (err) {
      setTerminalLogs(prev => [
        ...prev,
        `[ERROR] Simulation execution failed: ${String(err)}`
      ]);
    } finally {
      setRunningScenarioId(null);
    }
  };

  return (
    <div className="space-y-6">
      {/* Header and Reset Bar */}
      <div className="p-5 rounded-xl bg-gradient-to-r from-navy-900 via-navy-850 to-slate-900 border border-cyan-500/30 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 shadow-glow-cyan">
        <div className="flex items-center space-x-3">
          <div className="p-2.5 rounded-lg bg-cyan-500/10 text-cyan-accent border border-cyan-400/30">
            <Terminal className="w-6 h-6" />
          </div>
          <div>
            <div className="flex items-center space-x-2">
              <h2 className="text-sm font-semibold text-white font-mono">VELTRIX ATTACK SIMULATION LAB</h2>
              <span className="text-[10px] uppercase font-mono px-1.5 py-0.5 rounded bg-purple-500/20 text-purple-300 border border-purple-500/30 font-bold">
                COMPETITION HARNESS
              </span>
            </div>
            <p className="text-xs text-slate-400">
              Interactive sandbox injecting realistic cyber attack sequences directly into the live ingestion and correlation engine.
            </p>
          </div>
        </div>

        <button
          onClick={onReset}
          disabled={isResetting}
          className="flex items-center space-x-2 px-3 py-2 rounded-lg bg-slate-900 hover:bg-slate-800 text-xs font-mono text-slate-300 border border-slate-700 transition"
        >
          <RotateCcw className={`w-3.5 h-3.5 ${isResetting ? 'animate-spin text-cyan-accent' : ''}`} />
          <span>Reset Environment</span>
        </button>
      </div>

      {/* Execution Results Banner (if ran) */}
      {lastResult && (
        <div className="p-4 rounded-xl bg-navy-900 border border-cyan-500/50 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 shadow-glow-cyan">
          <div className="space-y-1">
            <div className="flex items-center space-x-2">
              <CheckCircle2 className="w-4 h-4 text-emerald-400" />
              <span className="text-xs font-mono font-bold text-white uppercase">
                Simulation Run Succeeded ({lastResult.durationMs}ms)
              </span>
              <span className="text-xs font-mono px-2 py-0.5 rounded bg-rose-500/20 text-rose-300 font-bold">
                Risk Score: {lastResult.riskScore} / 100
              </span>
            </div>
            <p className="text-xs text-slate-400">
              Generated {lastResult.injectedEventsCount} events &bull; Triggered {lastResult.triggeredRules.length} Sigma rules &bull; Correlated Incident: {lastResult.correlatedIncidentId}
            </p>
          </div>

          {lastResult.correlatedIncidentId && (
            <button
              onClick={() => onNavigateToIncident(lastResult.correlatedIncidentId!)}
              className="flex items-center space-x-1.5 px-4 py-2 rounded-lg bg-cyan-500 hover:bg-cyan-400 text-slate-950 text-xs font-mono font-bold shadow-glow-cyan transition shrink-0"
            >
              <span>Inspect Correlated Incident</span>
              <ArrowRight className="w-4 h-4" />
            </button>
          )}
        </div>
      )}

      {/* Scenarios Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
        {scenarios.map((scen) => {
          const isRunning = runningScenarioId === scen.id;
          const isCritical = scen.severity === 'CRITICAL';

          return (
            <div
              key={scen.id}
              className={`p-5 rounded-xl bg-navy-900 border flex flex-col justify-between transition ${
                isCritical ? 'border-rose-500/30 hover:border-rose-500/60' : 'border-slate-800 hover:border-slate-700'
              }`}
            >
              <div>
                <div className="flex items-center justify-between gap-2 mb-3">
                  <span className={`text-[10px] font-mono px-2 py-0.5 rounded font-bold ${
                    isCritical 
                      ? 'bg-rose-500/20 text-rose-300 border border-rose-500/40' 
                      : 'bg-amber-500/20 text-amber-300 border border-amber-500/40'
                  }`}>
                    {scen.severity}
                  </span>
                  <span className="text-[11px] font-mono text-slate-500">
                    {scen.eventsCount} Events &bull; ~{scen.estimatedDurationSeconds}s
                  </span>
                </div>

                <h3 className="text-sm font-bold text-white mb-2">{scen.name}</h3>
                <p className="text-xs text-slate-400 mb-4 leading-relaxed line-clamp-3">
                  {scen.description}
                </p>

                {/* Target & Tactics */}
                <div className="space-y-1.5 pt-3 border-t border-slate-800/80 text-[11px] font-mono text-slate-400 mb-5">
                  <div className="flex items-center justify-between">
                    <span className="text-slate-500">Target Identity:</span>
                    <span className="text-slate-200 truncate max-w-[140px]">{scen.targetUser}</span>
                  </div>
                  <div className="flex items-center justify-between">
                    <span className="text-slate-500">Adversary Source:</span>
                    <span className="text-cyan-accent">{scen.attackerIp}</span>
                  </div>
                  <div className="flex items-center justify-between">
                    <span className="text-slate-500">MITRE Tactics:</span>
                    <span className="text-slate-300">{scen.mitreTechniques.join(', ')}</span>
                  </div>
                </div>
              </div>

              <button
                onClick={() => handleRun(scen)}
                disabled={isRunning}
                className={`w-full py-2 px-3 rounded-lg flex items-center justify-center space-x-2 text-xs font-mono font-bold transition ${
                  isRunning
                    ? 'bg-slate-800 text-cyan-accent border border-cyan-500/40 animate-pulse'
                    : isCritical
                      ? 'bg-rose-500 hover:bg-rose-400 text-slate-950 shadow-glow-rose'
                      : 'bg-cyan-500 hover:bg-cyan-400 text-slate-950 shadow-glow-cyan'
                }`}
              >
                <Play className="w-3.5 h-3.5 fill-current" />
                <span>{isRunning ? 'Executing Scenario...' : 'Execute Simulation'}</span>
              </button>
            </div>
          );
        })}
      </div>

      {/* Live Telemetry Terminal */}
      <div className="rounded-xl bg-navy-950 border border-slate-800 overflow-hidden font-mono text-xs">
        <div className="bg-navy-900/90 px-4 py-2.5 border-b border-slate-800 flex items-center justify-between">
          <div className="flex items-center space-x-2">
            <span className="w-2.5 h-2.5 rounded-full bg-rose-500/80"></span>
            <span className="w-2.5 h-2.5 rounded-full bg-amber-500/80"></span>
            <span className="w-2.5 h-2.5 rounded-full bg-emerald-500/80"></span>
            <span className="text-slate-400 text-[11px] ml-2">veltrix-telemetry-stream.log</span>
          </div>
          <span className="text-[10px] text-cyan-400">STATUS: READY</span>
        </div>

        <div className="p-4 max-h-48 overflow-y-auto space-y-1 text-slate-300 select-text">
          {terminalLogs.map((line, idx) => (
            <div key={idx} className="flex items-start space-x-2 text-[11px]">
              <span className="text-slate-600 select-none">&gt;</span>
              <span className={
                line.includes('[ALERT]') || line.includes('Risk Score') 
                  ? 'text-rose-400 font-bold' 
                  : line.includes('[COMPLETED]') 
                    ? 'text-emerald-400 font-bold' 
                    : line.includes('[INJECT') 
                      ? 'text-cyan-accent' 
                      : 'text-slate-400'
              }>
                {line}
              </span>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
};
